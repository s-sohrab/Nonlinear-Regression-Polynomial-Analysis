# گام ۱: تولید داده‌های مصنوعی
import numpy as np
import matplotlib.pyplot as plt
from sklearn.preprocessing import PolynomialFeatures
from sklearn.linear_model import LinearRegression
from sklearn.metrics import mean_squared_error, r2_score
from sklearn.pipeline import make_pipeline

# تنظیم بذر تصادفی برای بازتولیدپذیری (Reproducibility)
np.random.seed(42)

# تولید ۱۰۰ نمونه در بازه ۰ تا ۵۰ (زمان)
x_nonlinear = np.linspace(0, 50, 100)

# تولید جمعیت باکتری با رابطه سینوسی + نویز نرمال (میانگین ۰، انحراف معیار ۵۰)
y_nonlinear = 1000 * np.sin(0.1 * x_nonlinear) + np.random.normal(0, 50, 100)

# تبدیل x به آرایه ستونی
X = x_nonlinear.reshape(-1, 1)

# گام ۲: رسم نمودار پراکندگی داده‌های خام
plt.figure(figsize=(10, 6))
plt.scatter(x_nonlinear, y_nonlinear, color='blue', alpha=0.6, label='داده‌های واقعی (با نویز)')
plt.title('نمودار پراکندگی: جمعیت باکتری بر اساس زمان')
plt.xlabel('زمان (x)')
plt.ylabel('جمعیت باکتری (y)')
plt.legend()
plt.grid(True)
plt.show()

# گام ۳: ساخت مدل با Pipeline (ترکیب PolynomialFeatures و LinearRegression)
degree = 3
model = make_pipeline(PolynomialFeatures(degree), LinearRegression())

# آموزش مدل روی داده‌ها
model.fit(X, y_nonlinear)

print(f"مدل درجه {degree} با موفقیت آموزش دید.")

# گام ۴: پیش‌بینی و محاسبه معیارهای خطا
y_pred = model.predict(X)

mse = mean_squared_error(y_nonlinear, y_pred)
r2 = r2_score(y_nonlinear, y_pred)

print(f"MSE (میانگین مربعات خطا): {mse:.2f}")
print(f"R2 Score (ضریب تعیین): {r2:.4f}")
print("-" * 30)
print("Coefficients (ضرایب):", model.named_steps['linearregression'].coef_)
print("Intercept (عرض از مبدأ):", model.named_steps['linearregression'].intercept_)

# گام ۵: بررسی تأثیر درجه چندجمله‌ای بر خطا (Overfitting)
print("بررسی تأثیر درجه چندجمله‌ای بر خطا (MSE):")
for d in [1, 2, 3, 5, 10]:
    poly_temp = PolynomialFeatures(degree=d)
    X_poly_temp = poly_temp.fit_transform(X)
    model_temp = LinearRegression()
    model_temp.fit(X_poly_temp, y_nonlinear)
    y_pred_temp = model_temp.predict(X_poly_temp)
    mse_temp = mean_squared_error(y_nonlinear, y_pred_temp)
    print(f"  درجه {d}: MSE = {mse_temp:.2f}")

from sklearn.model_selection import train_test_split

# ۱. جداسازی داده‌ها به نسبت ۸۰ به ۲۰
X_train, X_test, y_train, y_test = train_test_split(X, y_nonlinear, test_size=0.2, random_state=42)

print(f"تعداد داده‌های آموزش: {X_train.shape[0]}")
print(f"تعداد داده‌های تست: {X_test.shape[0]}")

# ۲. آموزش مجدد مدل درجه ۳ روی داده‌های آموزش
model_final = make_pipeline(PolynomialFeatures(degree=3), LinearRegression())
model_final.fit(X_train, y_train)

# ۳. ارزیابی روی داده‌های تست (داده‌هایی که مدل ندیده)
y_pred_test = model_final.predict(X_test)
mse_test = mean_squared_error(y_test, y_pred_test)
r2_test = r2_score(y_test, y_pred_test)

print(f"MSE (روی داده تست): {mse_test:.2f}")
print(f"R2 Score (روی داده تست): {r2_test:.4f}")

from sklearn.model_selection import cross_val_score

# انجام ۵-فولد کراس ولیدیشن روی کل داده‌ها
cv_scores = cross_val_score(model_final, X, y_nonlinear, cv=5, scoring='neg_mean_squared_error')
mse_cv = -cv_scores # تبدیل به مقدار مثبت

print(f"MSE در هر فولد: {mse_cv}")
print(f"میانگین MSE: {mse_cv.mean():.2f}")
print(f"انحراف معیار MSE: {mse_cv.std():.2f}")

print("درجه | MSE آموزش | MSE تست")
print("-" * 35)

for d in [1, 2, 3, 5, 10, 15]:
    temp_model = make_pipeline(PolynomialFeatures(d), LinearRegression())
    temp_model.fit(X_train, y_train)

    # خطا روی آموزش
    y_train_pred = temp_model.predict(X_train)
    mse_train = mean_squared_error(y_train, y_train_pred)

    # خطا روی تست
    y_test_pred = temp_model.predict(X_test)
    mse_test = mean_squared_error(y_test, y_test_pred)

    print(f"  {d:2}  |  {mse_train:10.2f}  |  {mse_test:10.2f}")

from sklearn.model_selection import GridSearchCV

# تعریف مدل پایه
base_model = make_pipeline(PolynomialFeatures(), LinearRegression())

# پارامترهای جستجو (درجه‌های ۱ تا ۷)
param_grid = {'polynomialfeatures__degree': [1, 2, 3, 4, 5, 6, 7]}

# جستجوی شبکه‌ای با کراس ولیدیشن ۵ تایی
grid_search = GridSearchCV(base_model, param_grid, cv=5, scoring='neg_mean_squared_error')
grid_search.fit(X_train, y_train)

print(f"بهترین درجه پیدا شده: {grid_search.best_params_['polynomialfeatures__degree']}")
print(f"بهترین MSE (روی اعتبارسنجی): {-grid_search.best_score_:.2f}")

# گام ۶: استفاده از بهترین مدل (درجه ۵) برای رسم نمودار نهایی
best_degree = 5
model_best = make_pipeline(PolynomialFeatures(best_degree), LinearRegression())
model_best.fit(X_train, y_train) # آموزش روی داده‌های Train

# ساخت بازه پیوسته برای رسم خط
x_plot = np.linspace(0, 50, 200).reshape(-1, 1)
y_plot = model_best.predict(x_plot)

plt.figure(figsize=(10, 6))
# رسم داده‌های آموزش و تست با رنگ‌های متفاوت
plt.scatter(X_train, y_train, color='blue', alpha=0.6, label='داده‌های آموزش')
plt.scatter(X_test, y_test, color='green', alpha=0.8, marker='^', label='داده‌های تست')
# رسم خط مدل بهینه
plt.plot(x_plot, y_plot, color='red', linewidth=2.5, label=f'مدل بهینه (درجه {best_degree})')

plt.title('رگرسیون غیرخطی: مدل بهینه با درجه ۵', fontsize=14)
plt.xlabel('زمان (x)', fontsize=12)
plt.ylabel('جمعیت باکتری (y)', fontsize=12)
plt.legend()
plt.grid(True)
plt.show()

